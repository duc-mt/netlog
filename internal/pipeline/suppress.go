// SuppressOwn drops log entries that are generated by netlog's own SSH polling
// sessions and carry no diagnostic value.  Every time netlog opens an SSH
// session to a VyOS (or any systemd-based) device, the device records several
// PAM / systemd housekeeping lines in its own log buffer:
//
//   pam_env(sshd:session): deprecated reading of user environment enabled
//   pam_unix(sshd:session): session opened for user nms-net(uid=1004) by (uid=0)
//   systemd[1]: Started Session 899 of User nms-net.
//   systemd-logind[986]: New session 899 of user nms-net.
//   systemd[1]: session-899.scope: Deactivated successfully.
//   opt-vyatta-config-tmp-new_config_283448.mount: Deactivated successfully.
//
// These are captured on the very next poll and inflate the "new log entries"
// counter, obscuring real events and feeding the anomaly detector with noise.
//
// The patterns are intentionally narrow: they match on process name plus the
// exact session-management verb so that real security events (e.g.
// "Failed password for nms-net", "Accepted publickey for nms-net") are never
// suppressed.
//
// Call order in the pipeline:
//
//	Watermarks.Filter → DropFuture → Normalize → ClassifyAll
//	  → Watermarks.Advance    ← must advance past suppressed entries
//	  → SuppressOwn           ← then drop them
//	  → store.Append          ← only clean entries hit disk
//	  → Detector.Observe
package pipeline

import (
	"regexp"

	"netlog/internal/collector"
)

// ownSessionPatterns match log lines that are produced solely by netlog's SSH
// polling sessions (PAM, systemd session tracking, VyOS config-mount units).
// They are compiled once at package init.  All patterns are case-insensitive.
var ownSessionPatterns = []*regexp.Regexp{
	// PAM environment deprecation warning emitted on every SSH login.
	regexp.MustCompile(`(?i)pam_env\(sshd:session\).*deprecated reading of user environment`),

	// PAM session open / close for the polling account.
	regexp.MustCompile(`(?i)pam_unix\(sshd:session\): session (?:opened|closed) for user`),

	// systemd session scope lifecycle ("Started Session N of User X" / "Removed …").
	regexp.MustCompile(`(?i)systemd\[1\]: (?:Started|Removed) Session \d+ of User`),

	// systemd-logind session tracking ("New session N of user X" / "Removed …").
	regexp.MustCompile(`(?i)systemd-logind\[\d+\]: (?:New|Removed) session \d+ of user`),

	// systemd session-N.scope unit activation / deactivation.
	regexp.MustCompile(`(?i)systemd\[1\]: session-\d+\.scope:`),

	// VyOS temporary config-mount units created during "show log" retrieval.
	regexp.MustCompile(`(?i)opt-vyatta-config-tmp-[^:]+\.mount:`),
}

// SuppressOwn returns a new slice that omits any entry whose Raw text matches
// one of the built-in own-session patterns.  If no entries are suppressed the
// original slice is returned unchanged (no allocation).
//
// The caller must have already advanced the watermark past the full (pre-
// suppression) batch so that suppressed entries are not re-presented on the
// next poll.
func SuppressOwn(entries []collector.LogEntry) []collector.LogEntry {
	// Fast path: scan without allocating until we find the first match.
	first := -1
	for i := range entries {
		if isOwnSession(entries[i].Raw) {
			first = i
			break
		}
	}
	if first == -1 {
		return entries // nothing to suppress
	}

	// Slow path: copy the entries that pass the filter.
	kept := make([]collector.LogEntry, 0, len(entries)-1)
	kept = append(kept, entries[:first]...)
	for _, e := range entries[first+1:] {
		if !isOwnSession(e.Raw) {
			kept = append(kept, e)
		}
	}
	return kept
}

// isOwnSession reports whether raw matches any own-session pattern.
func isOwnSession(raw string) bool {
	for _, re := range ownSessionPatterns {
		if re.MatchString(raw) {
			return true
		}
	}
	return false
}
